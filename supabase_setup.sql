    SET name = p_name
    WHERE public.users.id = v_id;
    
    RETURN QUERY
    SELECT u.id, u.name, u.email, u.plan, u.date, u.status, u.visits
    FROM public.users u
    WHERE u.id = v_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

