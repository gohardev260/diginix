-- Handle New Auth User Profile and Admin Sync Trigger
CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER AS $$
DECLARE
    v_role TEXT := 'user';
BEGIN
    IF EXISTS (SELECT 1 FROM public.admin_users WHERE LOWER(email) = LOWER(NEW.email)) THEN
        v_role := 'admin';
    END IF;

    INSERT INTO public.users (auth_user_id, name, email, plan, status, role, date)
    VALUES (
        NEW.id,
        COALESCE(NEW.raw_user_meta_data->>'full_name', 'User'),
        NEW.email,
        'Community',
        'Active',
        v_role,
        NOW()
    )
    ON CONFLICT (email) DO UPDATE
    SET auth_user_id = EXCLUDED.auth_user_id,
        role = v_role;
        
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

