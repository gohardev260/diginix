CREATE OR REPLACE FUNCTION public.get_public_stats()
RETURNS TABLE (
    revenue TEXT,
    activeusers TEXT,
    pro_users TEXT,
    visits INT8,
    revenuehistory TEXT,
    userhistory TEXT,
    visithistory TEXT
) AS $$
DECLARE
    v_user_count INT8;
    v_pro_count INT8;
    v_total_visits INT8;
    v_revenue_history TEXT;
    v_user_history TEXT;
    v_visit_history TEXT;
BEGIN
    -- Count of total users
    SELECT COUNT(*) INTO v_user_count FROM public.users;
    
    -- Count of Pro users
    SELECT COUNT(*) INTO v_pro_count FROM public.users WHERE plan = 'Pro';
    
    -- Count of total visits
    SELECT COALESCE(SUM(u.visits), 0) + (SELECT COUNT(*) FROM public.visit_logs WHERE email IS NULL OR email = '')
    INTO v_total_visits FROM public.users u;

    -- Calculate User History (Last 6 months user signups, e.g. '5,10,12,18,20,25')
    SELECT string_agg(count_val::text, ',') INTO v_user_history
    FROM (
        SELECT 
            COALESCE(COUNT(u.id), 0) AS count_val
        FROM generate_series(
            date_trunc('month', NOW() - INTERVAL '5 months'),
            date_trunc('month', NOW()),
            '1 month'::interval
        ) AS gs(dt)
        LEFT JOIN public.users u ON date_trunc('month', u.date) = gs.dt
        GROUP BY gs.dt
        ORDER BY gs.dt
    ) t;

    -- Calculate Visit History (Last 6 months visits, e.g. '10,15,30,45,60,75')
    SELECT string_agg(count_val::text, ',') INTO v_visit_history
    FROM (
        SELECT 
            COALESCE(COUNT(v.id), 0) AS count_val
        FROM generate_series(
            date_trunc('month', NOW() - INTERVAL '5 months'),
            date_trunc('month', NOW()),
            '1 month'::interval
        ) AS gs(dt)
        LEFT JOIN public.visit_logs v ON date_trunc('month', v.visited_at) = gs.dt
        GROUP BY gs.dt
        ORDER BY gs.dt
    ) t;

    -- Calculate Revenue History (Last 6 months cumulative Pro users * 1000 PKR, e.g. '2000,3000,5000,8000,10000,15000')
    SELECT string_agg(amount_val::text, ',') INTO v_revenue_history
    FROM (
        SELECT 
            (
                SELECT COUNT(*) 
                FROM public.users u 
                WHERE u.plan = 'Pro' 
                  AND u.date <= gs.dt + INTERVAL '1 month' - INTERVAL '1 second'
            ) * 1000 AS amount_val
        FROM generate_series(
            date_trunc('month', NOW() - INTERVAL '5 months'),
            date_trunc('month', NOW()),
            '1 month'::interval
        ) AS gs(dt)
        ORDER BY gs.dt
    ) t;

    RETURN QUERY
    SELECT 
        (v_pro_count * 1000 || ' PKR')::TEXT,
        v_user_count::TEXT,
        v_pro_count::TEXT,
        v_total_visits::INT8,
        COALESCE(v_revenue_history, '0,0,0,0,0,0')::TEXT,
        COALESCE(v_user_history, '0,0,0,0,0,0')::TEXT,
        COALESCE(v_visit_history, '0,0,0,0,0,0')::TEXT;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.get_public_stats() TO anon, authenticated;

