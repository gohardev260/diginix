-- User Profile security definer mutations (requires valid authenticated JWT session)
CREATE OR REPLACE FUNCTION public.update_profile_secure(p_name TEXT)
RETURNS TABLE (
    id BIGINT,
    name TEXT,
    email TEXT,
    plan TEXT,
    date TIMESTAMPTZ,
    status TEXT,
    visits INT
) AS $$
DECLARE
    v_id BIGINT;
BEGIN
    SELECT u.id INTO v_id FROM public.users u WHERE u.auth_user_id = auth.uid();
    
    IF v_id IS NULL THEN
        RAISE EXCEPTION 'Not authenticated or profile not found';
    END IF;

    -- Input Validation
    IF p_name IS NULL OR length(trim(p_name)) < 2 THEN
        RAISE EXCEPTION 'Name must be at least 2 characters long.';
