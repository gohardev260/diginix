-- Secure increment visit
CREATE OR REPLACE FUNCTION public.increment_user_visit_secure(
    p_email TEXT DEFAULT NULL,
    p_session_id UUID DEFAULT NULL
)
RETURNS INT AS $$
DECLARE
    v_id BIGINT;
    v_visits INT := 0;
    v_status TEXT;
    v_already_tracked BOOLEAN := FALSE;
BEGIN
    IF p_session_id IS NOT NULL THEN
        SELECT EXISTS (
            SELECT 1 FROM public.visit_logs WHERE session_id = p_session_id
        ) INTO v_already_tracked;
    END IF;

    IF NOT v_already_tracked THEN
        -- Log the visit in visit_logs
        INSERT INTO public.visit_logs (email, session_id, visited_at)
        VALUES (p_email, p_session_id, NOW());

        -- If a valid email is provided, also increment the user's visits count in public.users
        IF p_email IS NOT NULL AND p_email <> '' THEN
            SELECT u.id, u.status INTO v_id, v_status
            FROM public.users u
            WHERE LOWER(u.email) = LOWER(p_email);
              
            IF v_id IS NOT NULL AND (v_status IS NULL OR v_status <> 'Blocked') THEN
                UPDATE public.users
                SET visits = COALESCE(visits, 0) + 1
                WHERE public.users.id = v_id
                RETURNING public.users.visits INTO v_visits;
            END IF;
        END IF;
    ELSE
        IF p_email IS NOT NULL AND p_email <> '' THEN
            SELECT COALESCE(visits, 0) INTO v_visits
            FROM public.users
            WHERE LOWER(email) = LOWER(p_email);
        END IF;
    END IF;
    
    RETURN COALESCE(v_visits, 0);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.increment_user_visit_secure(TEXT, UUID) TO anon, authenticated;

-- Associate session visits to a logged-in user
CREATE OR REPLACE FUNCTION public.associate_session_visits(
    p_session_id UUID,
    p_email TEXT
)
RETURNS BOOLEAN AS $$
DECLARE
    v_id BIGINT;
    v_status TEXT;
    v_associated_count INT := 0;
BEGIN
    IF p_session_id IS NULL OR p_email IS NULL OR p_email = '' THEN
        RETURN FALSE;
    END IF;

    SELECT u.id, u.status INTO v_id, v_status
    FROM public.users u
    WHERE LOWER(u.email) = LOWER(p_email);

    IF v_id IS NULL OR v_status = 'Blocked' THEN
        RETURN FALSE;
    END IF;

    -- Update unassociated visit logs for this session
    WITH updated AS (
        UPDATE public.visit_logs
        SET email = p_email
        WHERE session_id = p_session_id 
          AND (email IS NULL OR email = '')
        RETURNING 1
    )
    SELECT COUNT(*) INTO v_associated_count FROM updated;

    IF v_associated_count > 0 THEN
        UPDATE public.users
        SET visits = COALESCE(visits, 0) + v_associated_count
        WHERE id = v_id;
    END IF;

    RETURN TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.associate_session_visits(UUID, TEXT) TO anon, authenticated;

-- Server-side filtering and aggregation for the admin portal user list
CREATE OR REPLACE FUNCTION public.get_filtered_users_admin(
    p_search TEXT DEFAULT NULL,
    p_start_date TIMESTAMPTZ DEFAULT NULL,
    p_end_date TIMESTAMPTZ DEFAULT NULL
)
RETURNS TABLE (
    name TEXT,
    email TEXT,
    date TIMESTAMPTZ,
    plan TEXT,
    status TEXT,
    range_visits INT,
    total_visits INT
) AS $$
BEGIN
    PERFORM public.verify_admin_only();

    RETURN QUERY
    SELECT 
        u.name,
        u.email,
        u.date,
        u.plan,
        u.status,
        COALESCE((
            SELECT COUNT(*)::INT
            FROM public.visit_logs v
            WHERE LOWER(v.email) = LOWER(u.email)
              AND (p_start_date IS NULL OR v.visited_at >= p_start_date)
              AND (p_end_date IS NULL OR v.visited_at <= p_end_date)
        ), 0) AS range_visits,
        COALESCE(u.visits, 0) AS total_visits
    FROM public.users u
    WHERE
        (p_search IS NULL OR p_search = '' OR
            LOWER(u.name) LIKE '%' || LOWER(p_search) || '%' OR
            LOWER(u.email) LIKE '%' || LOWER(p_search) || '%' OR
            LOWER(u.plan) LIKE '%' || LOWER(p_search) || '%' OR
            LOWER(u.status) LIKE '%' || LOWER(p_search) || '%'
        )
        AND
        (
            (p_start_date IS NULL AND p_end_date IS NULL) OR
            (u.date >= p_start_date AND u.date <= p_end_date) OR
            EXISTS (
                SELECT 1 
                FROM public.visit_logs v 
                WHERE LOWER(v.email) = LOWER(u.email) 
                  AND v.visited_at >= p_start_date 
                  AND v.visited_at <= p_end_date
            )
        )
    ORDER BY u.id DESC;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.get_filtered_users_admin(TEXT, TIMESTAMPTZ, TIMESTAMPTZ) TO authenticated;

