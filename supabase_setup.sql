-- Migration function to import existing users from public.users to auth.users (bcrypt migration)
CREATE OR REPLACE FUNCTION public.migrate_legacy_users()
RETURNS VOID AS $$
DECLARE
    r RECORD;
    v_new_uuid UUID;
BEGIN
    FOR r IN SELECT * FROM public.users WHERE auth_user_id IS NULL AND password IS NOT NULL AND password <> '' LOOP
        v_new_uuid := gen_random_uuid();
        
        IF NOT EXISTS (SELECT 1 FROM auth.users WHERE email = r.email) THEN
            INSERT INTO auth.users (
                id,
                instance_id,
                email,
                encrypted_password,
                email_confirmed_at,
                raw_app_meta_data,
                raw_user_meta_data,
                aud,
                role,
                created_at,
                updated_at,
                confirmation_token,
                recovery_token,
                email_change_token_new,
                email_change
            )
            VALUES (
                v_new_uuid,
                '00000000-0000-0000-0000-000000000000',
                r.email,
                r.password, -- existing bcrypt hash
                NOW(),
                '{"provider": "email", "providers": ["email"]}'::jsonb,
                json_build_object('full_name', r.name),
                'authenticated',
                'authenticated',
                r.date::timestamp,
                NOW(),
                '',
                '',
                '',
                ''
            );
            
            UPDATE public.users
            SET auth_user_id = v_new_uuid
            WHERE id = r.id;
        ELSE
            UPDATE public.users
            SET auth_user_id = (SELECT id FROM auth.users WHERE email = r.email)
            WHERE id = r.id;
        END IF;
    END LOOP;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

