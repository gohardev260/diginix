CREATE OR REPLACE FUNCTION public.update_user_status_secure(
    p_email TEXT,
    p_csrf_token TEXT
)
RETURNS TABLE (success BOOLEAN, status TEXT) AS $$
DECLARE
    v_status TEXT;
    v_new_status TEXT;
BEGIN
    PERFORM public.verify_admin_and_csrf(p_csrf_token);

    SELECT u.status INTO v_status FROM public.users u WHERE LOWER(u.email) = LOWER(p_email);
    IF v_status IS NULL THEN
        RAISE EXCEPTION 'User not found';
    END IF;

    v_new_status := CASE WHEN v_status = 'Blocked' THEN 'Active' ELSE 'Blocked' END;

    UPDATE public.users
    SET status = v_new_status
    WHERE LOWER(email) = LOWER(p_email);

    RETURN QUERY SELECT TRUE, v_new_status;
END;
