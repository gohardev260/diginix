-- Create User Profile from Supabase Auth
CREATE OR REPLACE FUNCTION public.create_user_profile_from_auth(
    p_auth_user_id UUID,
    p_name TEXT,
    p_email TEXT
)
RETURNS public.users AS $$
DECLARE
    v_user public.users;
BEGIN
    -- Input Validation
    IF p_email IS NULL OR p_email !~* '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$' THEN
        RAISE EXCEPTION 'Invalid email address format.';
    END IF;

    IF p_name IS NULL OR length(trim(p_name)) < 2 THEN
        RAISE EXCEPTION 'Name must be at least 2 characters long.';
    END IF;

    IF EXISTS (SELECT 1 FROM public.users WHERE LOWER(email) = LOWER(p_email)) THEN
        -- If profile already exists, link it and return it
        UPDATE public.users
        SET auth_user_id = p_auth_user_id
        WHERE LOWER(email) = LOWER(p_email)
        RETURNING * INTO v_user;
    ELSE
        -- Insert user profile. plan defaults to 'Community' via trigger
        INSERT INTO public.users (auth_user_id, name, email, password, status, date)
        VALUES (p_auth_user_id, p_name, p_email, NULL, 'Active', CURRENT_DATE)
        RETURNING * INTO v_user;
    END IF;
    
    RETURN v_user;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.create_user_profile_from_auth(UUID, TEXT, TEXT) TO authenticated, anon;

