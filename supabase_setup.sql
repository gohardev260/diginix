-- Secure increment visit
CREATE OR REPLACE FUNCTION public.increment_user_visit_secure()
RETURNS INT AS $$
DECLARE
    v_id BIGINT;
    v_visits INT;
    v_status TEXT;
BEGIN
    SELECT u.id, u.visits, u.status INTO v_id, v_visits, v_status
    FROM public.users u
    WHERE u.auth_user_id = auth.uid();
      
    IF v_id IS NULL THEN
        RAISE EXCEPTION 'Invalid session';
    END IF;

    IF v_status = 'Blocked' THEN
        RAISE EXCEPTION 'User is blocked';
    END IF;
    
    UPDATE public.users
    SET visits = COALESCE(visits, 0) + 1
    WHERE public.users.id = v_id
    RETURNING public.users.visits INTO v_visits;
    
    RETURN v_visits;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.increment_user_visit_secure() TO authenticated;

