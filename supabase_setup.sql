CREATE OR REPLACE FUNCTION public.get_public_stats()
RETURNS TABLE (
    revenue TEXT,
    activeusers TEXT,
    executions TEXT,
    visits INT8,
    revenuehistory TEXT
) AS $$
DECLARE
    v_user_count INT8;
    v_total_visits INT8;
    v_stat public.stats%ROWTYPE;
BEGIN
    SELECT COUNT(*) INTO v_user_count FROM public.users;
    SELECT SUM(COALESCE(u.visits, 0)) INTO v_total_visits FROM public.users u;
    SELECT * INTO v_stat FROM public.stats LIMIT 1;
    
    RETURN QUERY
    SELECT 
        COALESCE(v_stat.revenue, '$0')::TEXT,
        COALESCE(v_user_count, 0)::TEXT,
        COALESCE(v_stat.executions, '0')::TEXT,
        COALESCE(v_total_visits, 0)::INT8,
        COALESCE(v_stat.revenueHistory, '0,0,0,0,0,0')::TEXT;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

