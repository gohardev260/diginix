-- CSRF Token Generator
CREATE OR REPLACE FUNCTION public.generate_csrf_token()
RETURNS TABLE (
    csrf_token TEXT,
    expires_at TIMESTAMP WITH TIME ZONE
) AS $$
DECLARE
    v_token TEXT;
    v_user_id UUID;
    v_expires TIMESTAMP WITH TIME ZONE;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Not authenticated';
    END IF;

    v_token := encode(gen_random_bytes(32), 'hex');
    v_expires := NOW() + INTERVAL '1 hour';

    INSERT INTO public.csrf_tokens (user_id, token, expires_at)
    VALUES (v_user_id, v_token, v_expires);

    RETURN QUERY SELECT v_token, v_expires;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.generate_csrf_token() TO authenticated;

-- CSRF Token Verification Helper
CREATE OR REPLACE FUNCTION public.verify_csrf_token(p_token TEXT)
RETURNS BOOLEAN AS $$
DECLARE
    v_user_id UUID;
    v_exists BOOLEAN;
BEGIN
    v_user_id := auth.uid();
    IF v_user_id IS NULL THEN
        RETURN FALSE;
    END IF;

    SELECT EXISTS (
        SELECT 1 FROM public.csrf_tokens
        WHERE user_id = v_user_id
          AND token = p_token
          AND expires_at > NOW()
          AND used = FALSE
    ) INTO v_exists;

    IF v_exists THEN
        UPDATE public.csrf_tokens
        SET used = TRUE
        WHERE user_id = v_user_id AND token = p_token;
    END IF;

    RETURN v_exists;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Guard: Verify Admin Role only (Read Actions)
CREATE OR REPLACE FUNCTION public.verify_admin_only()
RETURNS BOOLEAN AS $$
DECLARE
    v_role TEXT;
BEGIN
    SELECT u.role INTO v_role 
    FROM public.users u 
    WHERE u.auth_user_id = auth.uid();
    
    IF v_role IS NULL OR v_role <> 'admin' THEN
        RAISE EXCEPTION 'Admin access required';
    END IF;
    RETURN TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Guard: Verify Admin Role and Validate CSRF (Write Actions)
CREATE OR REPLACE FUNCTION public.verify_admin_and_csrf(p_csrf_token TEXT)
RETURNS BOOLEAN AS $$
BEGIN
    PERFORM public.verify_admin_only();

    IF NOT public.verify_csrf_token(p_csrf_token) THEN
        RAISE EXCEPTION 'Invalid or expired security token. Please reload the page and try again.';
    END IF;

    RETURN TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

